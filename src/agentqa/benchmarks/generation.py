from __future__ import annotations

from typing import Any

from agentqa.models import BugCase
from agentqa.benchmarks.oracle import expected_for_args


def _numeric_variants(value: Any) -> list[Any]:
    if isinstance(value, bool):
        return []
    if isinstance(value, int):
        return [value - 1, 0, 1, value + 1]
    if isinstance(value, float):
        return [value - 1.0, 0.0, 1.0, value + 1.0]
    return []


def generate_boundary_tests(case: BugCase, limit: int = 6):
    """Generate deterministic boundary-oriented tests from public inputs.

    Only candidate inputs are generated by the agent baseline. Expected outputs
    are supplied by the benchmark oracle after generation, mirroring a developer-
    controlled executable specification in this synthetic study.
    """
    candidates: list[tuple[Any, ...]] = []
    for public in case.public_tests:
        args = list(public.args)
        for idx, arg in enumerate(args):
            for variant in _numeric_variants(arg):
                new = list(args); new[idx] = variant; candidates.append(tuple(new))
            if isinstance(arg, str):
                candidates.extend([tuple(args[:idx] + [arg.strip()] + args[idx+1:]), tuple(args[:idx] + [""] + args[idx+1:])])
            if isinstance(arg, list) and arg:
                candidates.append(tuple(args[:idx] + [arg[:1]] + args[idx+1:]))
        if len(args) >= 2 and isinstance(args[-1], int) and isinstance(args[0], list) and args[0]:
            for index in (0, len(args[0]) - 1):
                new = list(args); new[-1] = index; candidates.append(tuple(new))
    unique: list[tuple[Any, ...]] = []
    for c in candidates:
        if c not in unique and all(c != t.args for t in case.public_tests):
            unique.append(c)
        if len(unique) >= limit:
            break
    labelled = []
    for i, args in enumerate(unique):
        try:
            labelled.append(expected_for_args(case, args, f"generated_{i}"))
        except Exception:
            continue
    return tuple(labelled)
